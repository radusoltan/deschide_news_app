'use client';

import React, { useEffect, useRef, useState } from 'react';

interface StatItem {
  value: string;
  label: string;
  icon: string;
}

interface AnimatedStatsProps {
  items: StatItem[];
}

export function AnimatedStats({ items }: AnimatedStatsProps) {
  return (
    <div className="grid grid-cols-2 md:grid-cols-3 lg:grid-cols-6 gap-8">
      {items.map((stat, index) => (
        <StatCard key={index} stat={stat} index={index} />
      ))}
    </div>
  );
}

function StatCard({ stat, index }: { stat: StatItem; index: number }) {
  const [isVisible, setIsVisible] = useState(false);
  const ref = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const node = ref.current;
    const observer = new IntersectionObserver(
      ([entry]) => {
        if (entry.isIntersecting) {
          setIsVisible(true);
        }
      },
      { threshold: 0.1 }
    );

    if (node) {
      observer.observe(node);
    }

    return () => {
      if (node) {
        observer.unobserve(node);
      }
    };
  }, []);

  return (
    <div
      ref={ref}
      className="group text-center p-6 bg-gradient-to-br from-white to-slate-50 dark:from-slate-800 dark:to-slate-900 rounded-2xl shadow-lg hover:shadow-2xl transition-all duration-300 hover:-translate-y-2 border border-slate-200 dark:border-slate-700"
      style={{ animationDelay: `${index * 100}ms` }}
    >
      <div className="mb-4 flex justify-center">
        <div className="w-16 h-16 bg-gradient-to-br from-brand-tomato-500 to-red-600 rounded-xl flex items-center justify-center shadow-lg group-hover:scale-110 transition-transform duration-300">
          <IconComponent icon={stat.icon} />
        </div>
      </div>

      <div
        className={`text-4xl md:text-5xl font-black text-gray-900 dark:text-white mb-2 transition-all duration-1000 ${
          isVisible ? 'opacity-100 translate-y-0' : 'opacity-0 translate-y-4'
        }`}
      >
        {stat.value}
      </div>

      <div className="text-sm md:text-base font-semibold text-gray-600 dark:text-gray-400">
        {stat.label}
      </div>
    </div>
  );
}

